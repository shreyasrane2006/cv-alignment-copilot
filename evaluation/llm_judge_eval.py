"""
llm_judge_eval.py -- one-off script, NOT part of the live app.

LLM-as-judge evaluation of the two open-ended outputs this project has NO
other quantified evaluation for: the Interviewer's probing questions and
the Critic's improvement_suggestion bullets. RQ2 already has real,
human-adjudicated ground truth for verdict-label correctness (see
export_disagreements_for_adjudication.py / adjudication_report.py) -- this
script deliberately does NOT re-judge the verdict label itself, since that
would just duplicate RQ2 with a weaker, more self-biased method.

Uses REAL data: every {question, answer, verdict, improvement_suggestion}
tuple already sitting in session_log_*.json from actual usage (both the
scripted RQ1 batch and real manual testing), not synthetic samples.

IMPORTANT METHODOLOGICAL CAVEAT (disclose this in the write-up): the only
model available here is qwen3:8b, zero-cost/fully-offline with a 6GB VRAM
budget -- there is no independent/larger judge model to call instead. The
judge is the same model (fresh context, temperature 0, an explicit
"be a strict critic, don't default to high scores" instruction) grading
outputs generated by that same model elsewhere in the pipeline. This is a
well-documented "self-preference" bias risk in the LLM-as-judge literature,
not eliminated here, only somewhat reduced by the fresh-context + strict-
rubric framing. Cross-check a sample of the lowest and highest scoring
cases by hand before treating this as a fully independent measure.

Usage:
    python llm_judge_eval.py
Output:
    llm_judge_summary.json   (per-case scores/reasons + aggregate stats)
"""
import glob
import json

from llm_client import generate_structured, PARSING_MODEL, PARSING_TEMPERATURE
from judge_schemas import JudgeVerdict

SYSTEM_PROMPT = """You are a strict, critical evaluator reviewing outputs \
from an AI CV-feedback co-pilot. You are NOT being asked whether the \
verdict label (Match/Partial Match/No Match) was correct -- only whether \
the QUESTION that was asked and the IMPROVEMENT SUGGESTION that was given \
are actually good, on two separate 1-5 scales.

CRITICAL RULES:
- Do NOT default to high scores. Most real outputs are decent-but-flawed, \
not excellent -- use the full 1-5 range, and reserve 5 for outputs with no \
real flaw. Grade critically, like a strict reviewer, not a generous one.
- QUESTION QUALITY: a 5 is specific to the requirement, genuinely \
open-ended (doesn't presume the answer), and personalized to real CV \
content if a grounding_reference was given. A 1-2 is a generic checklist \
question that could be asked of any candidate, or is yes/no phrased, or \
assumes the answer.
- SUGGESTION QUALITY: a 5 is a concrete CV bullet built ONLY from details \
the candidate actually stated in their answer, correctly calibrated to the \
verdict (e.g. for a No Match, it should say what's needed to earn a real \
Match, not just restate the gap in different words). A 1-2 is generic \
advice ("add more detail about X"), or invents specifics the candidate \
never actually said, or is just a restatement of the requirement.
- Judge each dimension independently -- a great question with a weak \
suggestion (or vice versa) should get two different scores, not one \
averaged impression.
"""


def load_real_cases() -> list[dict]:
    REQUIRED = ("requirement", "question", "answer", "verdict_label", "improvement_suggestion")
    cases = []
    skipped = 0
    for filepath in sorted(glob.glob("session_log_*.json")):
        with open(filepath, "r", encoding="utf-8") as f:
            log = json.load(f)
        for entry in log.get("transcript", []):
            if entry.get("type") != "answer":
                continue
            # A few of the oldest logs (2026-08-04, before improvement_suggestion
            # existed as a field at all) don't have every key -- skip rather than
            # crash, same "don't trust pre-fix data as-is" stance the project
            # already takes for pre-2026-08-15 ΔS values.
            if not all(k in entry for k in REQUIRED):
                skipped += 1
                continue
            cases.append({
                "source_file": filepath,
                "requirement": entry["requirement"],
                "question": entry["question"],
                "grounding_reference": entry.get("grounding_reference"),
                "answer": entry["answer"],
                "verdict_label": entry["verdict_label"],
                "improvement_suggestion": entry["improvement_suggestion"],
            })
    if skipped:
        print(f"[info] Skipped {skipped} older transcript entry(ies) missing required fields "
              f"(pre-improvement_suggestion schema)")
    return cases


def judge_case(case: dict) -> JudgeVerdict:
    user_content = (
        f"Requirement: {case['requirement']}\n"
        f"Grounding reference (CV context the question was anchored to, if any): "
        f"{case['grounding_reference'] or '(none -- asked cold)'}\n"
        f"Question asked: {case['question']}\n\n"
        f"Candidate's answer: {case['answer']}\n"
        f"Verdict given: {case['verdict_label']}\n"
        f"Improvement suggestion given: {case['improvement_suggestion']}"
    )
    return generate_structured(
        model=PARSING_MODEL,
        temperature=PARSING_TEMPERATURE,
        response_model=JudgeVerdict,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_content},
        ],
    )


def main():
    cases = load_real_cases()
    total = len(cases)
    print(f"{total} real case(s) to judge, loaded from session_log_*.json")

    results = []
    for i, case in enumerate(cases, 1):
        print(f"[{i}/{total}] {case['source_file']} :: {case['requirement'][:50]}")
        verdict = judge_case(case)
        print(f"   -> question={verdict.question_quality_score}/5, "
              f"suggestion={verdict.suggestion_quality_score}/5")
        results.append({**case, **verdict.model_dump()})

    q_scores = [r["question_quality_score"] for r in results]
    s_scores = [r["suggestion_quality_score"] for r in results]

    def _dist(scores):
        return {str(n): scores.count(n) for n in range(1, 6)}

    summary = {
        "total_cases": total,
        "question_quality": {
            "mean": round(sum(q_scores) / total, 2) if total else 0.0,
            "distribution": _dist(q_scores),
        },
        "suggestion_quality": {
            "mean": round(sum(s_scores) / total, 2) if total else 0.0,
            "distribution": _dist(s_scores),
        },
        "cases": results,
    }

    with open("llm_judge_summary.json", "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    print(f"\nDone. Question quality mean: {summary['question_quality']['mean']}/5, "
          f"Suggestion quality mean: {summary['suggestion_quality']['mean']}/5")
    print(f"Full breakdown saved to llm_judge_summary.json")


if __name__ == "__main__":
    main()
